#!/usr/bin/env python3
"""Pack the engine-fixed 16-friend SVGs (round3_engine/svg) into companions-v167.js.

Uses the v165 packer mapping (tools/build_companions_v165.py) pointed at the
fixed files, plus Art Director's slim emitter (single-quoted bodies, shared
duplicate f/m eggs) from pack/measure_pack.py. Also packs the four Phoenix
star-figure bodies for the Inner look at stages 3–6.

Does not edit official Dragon sources, engine.min.js, dragon.min.json, or
recipes.js. The official Dragon egg is packed from the byte-identical copy
in round3_engine/svg.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

ROOT = Path("/workspace/reading-app-math")
R3E = Path("/workspace/art/companions-upgrade/round3_engine")
OUT = ROOT / "companions-v167.js"
MAN = json.loads((R3E / "src" / "MANIFEST.json").read_text(encoding="utf-8"))

ORDER_KINDS = [
    "dragon", "bee", "turtle", "fern", "owl", "fox", "moth", "phoenix", "lamp",
    "suntiger", "lioncub", "firefly", "mosshedgehog", "glowcap", "axolotl", "highlandcow",
]

def builder_src():
    S = {}
    def add(kind, sex, st, p):
        S.setdefault(kind, {}).setdefault(sex or "", {})[st] = Path(p)
    echo = Path("/workspace/art/new-companions-v42/dragon_echo_option")
    for st in ("hatchling", "young", "grown", "wise"):
        add("dragon", None, st, echo / f"dragon-A3-echo-{st}.svg")
    add("dragon", None, "egg", "/workspace/art/new-companions-v42/svg/eggs/dragon-egg.svg")
    db = Path("/workspace/art/companions-dragonbase/v3/svg")
    for st in ("egg", "hatchling", "young", "grown", "wise"):
        add("bee", None, st, db / f"bee-db-{st}.svg")
        add("turtle", None, st, db / f"turtle-db-{st}.svg")
    b1 = Path("/workspace/art/companions-upgrade/batch1/svg")
    for st in ("egg", "hatchling", "young", "grown", "wise"):
        add("fern", None, st, b1 / f"fern-{st}.svg")
        add("owl", None, st, b1 / f"owl-{st}.svg")
        add("moth", None, st, b1 / f"moth-{st}.svg")
        for sex in ("female", "male"):
            add("fox", sex[0], st, b1 / f"fox-{sex}-{st}.svg")
    r3 = Path("/workspace/art/companions-upgrade/round3/svg")
    b2a = Path("/workspace/art/companions-upgrade/batch2a/svg")
    b2b = Path("/workspace/art/companions-upgrade/batch2b/svg")
    for st in ("egg", "hatchling", "young", "grown", "wise"):
        add("phoenix", None, st, r3 / f"phoenix-{st}.svg")
        add("lamp", None, st, r3 / f"lamp-{st}.svg")
        for sex in ("female", "male"):
            add("suntiger", sex[0], st, b2a / f"sun-tiger-{sex}-{st}.svg")
            add("lioncub", sex[0], st, b2a / f"lion-cub-{sex}-{st}.svg")
            add("firefly", sex[0], st, b2a / f"firefly-{sex}-{st}.svg")
            add("mosshedgehog", sex[0], st, b2b / f"moss-hedgehog-{sex}-{st}.svg")
            add("glowcap", sex[0], st, r3 / f"glowcap-{sex}-{st}.svg")
            add("axolotl", sex[0], st, r3 / f"axolotl-{sex}-{st}.svg")
            add("highlandcow", sex[0], st, r3 / f"highland-cow-{sex}-{st}.svg")
    return S

def fixed_src():
    inv = {v: k for k, v in MAN.items()}
    S = builder_src()
    missing = []
    for kind in S:
        for sex in S[kind]:
            for st in list(S[kind][sex]):
                key = str(S[kind][sex][st])
                if key not in inv:
                    missing.append(key)
                    continue
                p = R3E / "svg" / inv[key]
                if not p.is_file():
                    missing.append(str(p))
                S[kind][sex][st] = p
    if missing:
        raise SystemExit("missing fixed SVG mapping:\n" + "\n".join(missing))
    return S

STYLE_RE = re.compile(r"<style[^>]*>[\s\S]*?</style>", re.I)

def inner(p: Path) -> str:
    t = re.sub(r"^<\?xml[^?]*\?>\s*", "", p.read_text(encoding="utf-8").strip())
    m = re.search(r"<svg\b([^>]*)>([\s\S]*)</svg>\s*$", t, re.I)
    if not m:
        raise SystemExit(f"no svg root in {p}")
    return re.sub(r">\s+<", "><", STYLE_RE.sub("", m.group(2))).strip()

def payload(S, css_src: Path):
    art = {k: {sx: {st: inner(p) for st, p in sts.items()} for sx, sts in sexes.items()} for k, sexes in S.items()}
    css = re.search(r"<style[^>]*>([\s\S]*?)</style>", css_src.read_text(encoding="utf-8")).group(1).strip()
    starfig = {ph: inner(R3E / "svg" / f"phoenix-starfig-{short}.svg")
               for ph, short in (("hatchling", "hatch"), ("young", "young"), ("grown", "grown"), ("wise", "wise"))}
    return {"css": css, "art": art, "starfig": starfig}

def sq(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029") + "'"

def key(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z_$][\w$]*", k) else sq(k)

HEADER = """/* v167 companion art pack. Generated by tools/build_companions_v167.py.
   Engine-fixed SVGs from companions-upgrade/round3_engine/svg (Bee/Turtle
   il-accent, .il-sp sparks, slimmer markup) plus Phoenix star figures for
   the Inner look at stages 3-6. Slim emitter: single-quoted bodies, shared
   duplicate f/m eggs (Art Director drop-in from pack/measure_pack.py).
   Official Dragon files, engine.min.js, dragon.min.json and recipes.js were
   not edited. */
"""

def emit_slim(P) -> str:
    seen = {}
    for k, sexes in P["art"].items():
        for sx, sts in sexes.items():
            for st, b in sts.items():
                seen[b] = seen.get(b, 0) + 1
    shared = {b: f"s{i}" for i, b in enumerate(b for b, n in seen.items() if n > 1)}
    parts = []
    for k, sexes in P["art"].items():
        sp = []
        for sx, sts in sexes.items():
            sp.append(key(sx) + ":{" + ",".join(key(st) + ":" + (shared[b] if b in shared else sq(b)) for st, b in sts.items()) + "}")
        parts.append(key(k) + ":{" + ",".join(sp) + "}")
    decl = ("var " + ",".join(f"{v}={sq(b)}" for b, v in shared.items()) + ";\n") if shared else ""
    star = "{" + ",".join(key(ph) + ":" + sq(body) for ph, body in P["starfig"].items()) + "}"
    return (HEADER
            + "(function(root){\n'use strict';\n" + decl
            + "root.IL165ART={css:" + sq(P["css"]) + ",art:{" + ",".join(parts) + "},starfig:" + star + "};\n"
            + "})(typeof window!=='undefined'?window:this);\n")

def main() -> None:
    S = fixed_src()
    P = payload(S, R3E / "svg" / "phoenix-grown.svg")
    # hygiene
    missing_acc, missing_sp, n = [], [], 0
    for kind, sexes in P["art"].items():
        for sx, sts in sexes.items():
            for st, body in sts.items():
                n += 1
                n_acc = body.count("il-accent")
                n_sp = len(re.findall(r'class="il-sp"', body))
                if st == "egg":
                    if n_acc: missing_acc.append(f"{kind}:{sx}:{st} has {n_acc} accent")
                    if n_sp: missing_sp.append(f"{kind}:{sx}:{st} has spark")
                else:
                    if n_acc != 1: missing_acc.append(f"{kind}:{sx}:{st} accents={n_acc}")
                    if n_sp != 1: missing_sp.append(f"{kind}:{sx}:{st} sparks={n_sp}")
    if n != 120:
        raise SystemExit(f"expected 120 bodies, got {n}")
    if missing_acc or missing_sp:
        raise SystemExit("hygiene fail:\n" + "\n".join(missing_acc + missing_sp))
    for ph, body in P["starfig"].items():
        if 'data-starfig="phe"' not in body:
            raise SystemExit(f"starfig {ph} missing data-starfig=phe")
    text = emit_slim(P)
    OUT.write_text(text, encoding="utf-8")
    raw = len(text.encode("utf-8"))
    src_bytes = sum(p.stat().st_size for sexes in S.values() for sts in sexes.values() for p in sts.values())
    print(f"wrote {OUT} ({raw} B, {raw/1024/1024:.3f} MiB); 120 files + 4 starfig; svg sources {src_bytes} B")
    if raw > 920_000:
        print("WARN pack larger than the 0.86 MiB slim target", file=sys.stderr)

if __name__ == "__main__":
    main()
