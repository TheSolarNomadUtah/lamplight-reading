#!/usr/bin/env python3
"""Pack the 16-friend v165 SVGs into companions-v165.js. Reads Art Director
source folders only; does not modify official Dragon sources, engine.min.js,
dragon.min.json, or recipes.js."""
from __future__ import annotations
import json, re, sys
from pathlib import Path

ROOT = Path("/workspace/reading-app-math")
OUT = ROOT / "companions-v165.js"

# kind -> (sex or None) -> stage -> path
SRC = {}

def add(kind, sex, stage, path):
    p = Path(path)
    if not p.is_file():
        raise SystemExit(f"missing SVG: {p}")
    SRC.setdefault(kind, {}).setdefault(sex or "", {})[stage] = p

# Dragon: A3 pearl echo for the four sitting stages; official egg used as-is (not edited).
echo = Path("/workspace/art/new-companions-v42/dragon_echo_option")
for st in ("hatchling", "young", "grown", "wise"):
    add("dragon", None, st, echo / f"dragon-A3-echo-{st}.svg")
add("dragon", None, "egg", "/workspace/art/new-companions-v42/svg/eggs/dragon-egg.svg")

db = Path("/workspace/art/companions-dragonbase/v3/svg")
for st in ("egg", "hatchling", "young", "grown", "wise"):
    add("bee", None, st, db / f"bee-db-{st}.svg")
    add("turtle", None, st, db / f"turtle-db-{st}.svg")

b1 = Path("/workspace/art/companions-upgrade/batch1/svg")
for st in ("egg", "hatchling", "young", "grown", "wise"):
    add("fern", None, st, b1 / f"fern-{st}.svg")
    add("owl", None, st, b1 / f"owl-{st}.svg")
    add("moth", None, st, b1 / f"moth-{st}.svg")
    for sex in ("female", "male"):
        add("fox", sex[0], st, b1 / f"fox-{sex}-{st}.svg")

r3 = Path("/workspace/art/companions-upgrade/round3/svg")
b2a = Path("/workspace/art/companions-upgrade/batch2a/svg")
b2b = Path("/workspace/art/companions-upgrade/batch2b/svg")
for st in ("egg", "hatchling", "young", "grown", "wise"):
    add("phoenix", None, st, r3 / f"phoenix-{st}.svg")  # round3, not batch2a
    add("lamp", None, st, r3 / f"lamp-{st}.svg")
    for sex in ("female", "male"):
        add("suntiger", sex[0], st, b2a / f"sun-tiger-{sex}-{st}.svg")
        add("lioncub", sex[0], st, b2a / f"lion-cub-{sex}-{st}.svg")
        add("firefly", sex[0], st, b2a / f"firefly-{sex}-{st}.svg")
        add("mosshedgehog", sex[0], st, b2b / f"moss-hedgehog-{sex}-{st}.svg")
        add("glowcap", sex[0], st, r3 / f"glowcap-{sex}-{st}.svg")  # round3, not batch2b
        add("axolotl", sex[0], st, r3 / f"axolotl-{sex}-{st}.svg")
        add("highlandcow", sex[0], st, r3 / f"highland-cow-{sex}-{st}.svg")

STYLE_RE = re.compile(r"<style[^>]*>[\s\S]*?</style>", re.I)
XMLNS_RE = re.compile(r"\sxmlns(?::\w+)?=\"[^\"]*\"")

def inner_markup(path: Path) -> str:
    t = path.read_text(encoding="utf-8")
    t = t.strip()
    # drop XML declaration
    t = re.sub(r"^<\?xml[^?]*\?>\s*", "", t)
    m = re.search(r"<svg\b([^>]*)>([\s\S]*)</svg>\s*$", t, re.I)
    if not m:
        raise SystemExit(f"no svg root in {path}")
    body = m.group(2)
    body = STYLE_RE.sub("", body)
    # keep defs and geometry; tidy whitespace a little
    body = re.sub(r">\s+<", "><", body).strip()
    return body

art = {}
counts = 0
bytes_in = 0
missing_accent = []
for kind, sexes in SRC.items():
    art[kind] = {}
    for sex, stages in sexes.items():
        art[kind][sex] = {}
        for st, path in stages.items():
            body = inner_markup(path)
            art[kind][sex][st] = body
            counts += 1
            bytes_in += path.stat().st_size
            raw = path.read_text(encoding="utf-8")
            n_acc = raw.count("il-accent")
            if st != "egg" and n_acc == 0:
                missing_accent.append(f"{kind}:{sex or '-'}{st}")

# shared CSS (from a typical packed SVG, once)
sample = Path("/workspace/art/companions-upgrade/round3/svg/phoenix-grown.svg").read_text()
sm = re.search(r"<style[^>]*>([\s\S]*?)</style>", sample)
css = sm.group(1).strip() if sm else ""

header = """/* v165 companion art pack. Generated by tools/build_companions_v165.py.
   Sources: Dragon A3 echo (+ official egg, unmodified), Bee and Ripple Turtle
   from companions-dragonbase/v3, batch1, batch2a (Sun Tiger, Lion, Firefly),
   batch2b (Moss only), round3 (Phoenix, Lamp, Glowcap, Axolotl, Highland Cow).
   Official Dragon files, engine.min.js, dragon.min.json and recipes.js were
   not edited. */
"""
payload = {"css": css, "art": art}
js = header + "(function(root){\n'use strict';\nroot.IL165ART=" + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n})(typeof window!=='undefined'?window:this);\n"
OUT.write_text(js, encoding="utf-8")
print("wrote", OUT, "files", counts, "source_bytes", bytes_in, "out_bytes", OUT.stat().st_size)
if missing_accent:
    print("no il-accent (non-egg):", ", ".join(missing_accent))
